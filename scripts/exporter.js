// Formats decoded design system data into DESIGN.md, tokens.css, and W3C Design Tokens JSON.

export function buildDesignMd(data) {
  const paletteRows = (data.palette || [])
    .map((c) => `| ${c.role} | \`${c.varName}\` | \`${c.hex}\` | \`${c.oklch}\` | ${c.share}% | ${c.contrast}:1 (${c.grade}) |`)
    .join("\n");

  const typeRows = (data.typography?.scale || [])
    .map((t) => `| ${t.role} (\`<${t.tag}>\`) | \`${t.size}\` | \`${t.lineHeight}\` | \`${t.tracking}\` | \`${t.weight}\` | ${t.sample} |`)
    .join("\n");

  const radiiRows = (data.radii || [])
    .map((r) => `- **${r.label}**: \`${r.radius}\` (${r.usage})`)
    .join("\n");

  const varLines = (data.cssVars || [])
    .slice(0, 12)
    .map((v) => `  ${v.name}: ${v.value};`)
    .join("\n");

  return `# DESIGN.md — ${data.domain}

> Source: \`${data.url}\`
> Telemetry: ${data.scannedNodes} visible DOM nodes · ${data.scanMs}ms

## 1. Area-Weighted Palette

| Role | Token | HEX | OKLCH | Area Share | Contrast (WCAG) |
|---|---|---|---|---|---|
${paletteRows}

## 2. Typography Hierarchy

- **Primary Font**: \`${data.typography?.primaryFont || "system-ui"}\`
- **Monospace Font**: \`${data.typography?.monoFont || "ui-monospace"}\`
- **Active Weights**: \`${(data.typography?.weights || [400, 500, 600]).join(" / ")}\`

| Role | Size | Line-Height | Tracking | Weight | Live Specimen |
|---|---|---|---|---|---|
${typeRows}

## 3. Surface & Concentric Radii

${radiiRows}

## 4. Root CSS Custom Properties

\`\`\`css
:root {
${varLines}
}
\`\`\`
`;
}

export function buildTokensCss(data) {
  const paletteVars = (data.palette || [])
    .map((c) => `  ${c.varName}: ${c.hex}; /* ${c.oklch} · ${c.share}% */`)
    .join("\n");
  const extraVars = (data.cssVars || [])
    .filter((v) => !(data.palette || []).some((p) => p.varName === v.name))
    .slice(0, 16)
    .map((v) => `  ${v.name}: ${v.value};`)
    .join("\n");
  return `/* Generated by Design Decoder — ${data.domain} */\n:root {\n${paletteVars}\n${extraVars ? extraVars + "\n" : ""}  --font-primary: ${data.typography?.primaryFont || "system-ui"};\n  --font-mono: ${data.typography?.monoFont || "monospace"};\n}\n`;
}

export function buildTokensJson(data) {
  return JSON.stringify(
    {
      $schema: "https://tr.designtokens.org/format/",
      meta: {
        domain: data.domain,
        url: data.url,
        scannedNodes: data.scannedNodes
      },
      color: Object.fromEntries(
        (data.palette || []).map((c) => [
          c.varName.replace(/^--/, ""),
          { $value: c.hex, oklch: c.oklch, role: c.role, areaShare: c.share, contrast: c.contrast }
        ])
      ),
      typography: data.typography,
      radii: data.radii
    },
    null,
    2
  );
}
